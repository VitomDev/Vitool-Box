let currentLanguage = 'en';

function systemLanguage() {
  for (const tag of navigator.languages || [navigator.language || 'en']) {
    if (STRINGS[tag]) return tag;
    const base = tag.split('-')[0].toLowerCase();
    if (base === 'pt') return 'pt-BR';
    if (base === 'zh') return 'zh-CN';
    if (STRINGS[base]) return base;
  }
  return 'en';
}

function setLanguage(choice) {
  currentLanguage = choice && STRINGS[choice] ? choice : systemLanguage();
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll('[data-i18n]').forEach((node) => { node.textContent = t(node.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach((node) => { node.title = t(node.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => { node.placeholder = t(node.dataset.i18nPlaceholder); });
}

function t(key, params) {
  const text = (STRINGS[currentLanguage] && STRINGS[currentLanguage][key]) || STRINGS.en[key] || key;
  return params ? text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? params[name] : match)) : text;
}

// Error keys from VitoolBox.exe: "checksum" or "installerCode|5".
function errorText(error) {
  const [key, code] = String(error).split('|');
  return STRINGS.en[`err.${key}`] ? t(`err.${key}`, { code }) : t('err.unknown');
}

function categoryName(category) {
  return STRINGS.en[`cat.${category}`] ? t(`cat.${category}`) : category;
}
